CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL CHECK (length(trim(category_name)) > 0),
    slug VARCHAR(120) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    category_image VARCHAR(500),
    is_visible BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
    product_name VARCHAR(255) NOT NULL CHECK (length(trim(product_name)) > 0),
    product_description TEXT,
    product_price NUMERIC(10, 2) NOT NULL CHECK (product_price >= 0),
    product_images JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(product_images) = 'array'),
    product_attributes JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(product_attributes) = 'object'),
    is_visible BOOLEAN NOT NULL DEFAULT TRUE,
    product_quantity INT NOT NULL DEFAULT 0 CHECK (product_quantity >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX products_category_idx ON products(category_id);
CREATE INDEX products_visible_newest_idx ON products(created_at DESC, product_id DESC) WHERE is_visible = TRUE;
